// Start the mobile project in HBuilderX Web mode before running this browser check.
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const { chromium } = require(path.resolve(__dirname, '../../nexus-console/node_modules/playwright'));
const { expect } = require(path.resolve(__dirname, '../../nexus-console/node_modules/@playwright/test'));
const assert = require('node:assert/strict');
const output = process.env.NEXUS_MOBILE_TEST_ARTIFACT_DIR || path.join(os.tmpdir(), 'nexus-mobile-planet-check');
const baseURL = process.env.NEXUS_MOBILE_TEST_BASE_URL || 'http://localhost:5173/';
fs.mkdirSync(output, { recursive: true });
(async () => {
 const browser = await chromium.launch({channel:'chrome',headless:true,chromiumSandbox:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 try {
  const context = await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  const page = await context.newPage();
  const errors = [];
  const apiCalls = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => {if(m.type()==='error') console.log('Browser error:',m.text().slice(0,350));});
  await context.route('**/*', route => {
   const url = new URL(route.request().url());
   if(/^\/(api|v1)(\/|$)/.test(url.pathname)){apiCalls.push(url.pathname);return route.abort();}
   return route.continue();
  });
  await page.goto(baseURL,{waitUntil:'networkidle',timeout:25000});
  await expect(page.locator('.planet-host')).toHaveAttribute('data-planet-state','ready',{timeout:25000});
  await expect(page.getByText('左右拖动旋转',{exact:true})).toBeVisible();
  const canvas=page.locator('.planet-host canvas');
  assert.equal(await canvas.count(),1);
  await page.screenshot({path:output+'/nexus-mobile-login-3d.png',fullPage:true});
  const before=await canvas.screenshot();
  const box=await canvas.boundingBox();
  await page.mouse.move(box.x+box.width*.4,box.y+box.height*.5);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*.75,box.y+box.height*.5,{steps:12});
  await page.mouse.up();
  const after=await canvas.screenshot();
  assert.notDeepEqual(before,after,'Dragging should change the rendered scene');
  await page.locator('.planet-reset').click();
  await page.screenshot({path:output+'/nexus-mobile-login-3d-reset.png',fullPage:true});
  console.log('3D ready; one WebGL canvas; horizontal drag changes rendered pixels; reset reachable');
  await page.locator('.login-page .nexus-button--block').click();
  await expect(page.locator('.nexus-field__message--error')).toHaveCount(2);
  assert.equal(apiCalls.length,0);
  console.log('Login form remains usable; business API requests: 0');
  await page.evaluate(()=>{getCurrentPages()[0].$vm.planetActive=false;});
  await expect(page.locator('.planet-host canvas')).toHaveCount(0);
  await expect(page.locator('.planet-poster')).toBeVisible();
  console.log('Inactive page stops rendering and restores poster');
  await page.evaluate(()=>{getCurrentPages()[0].$vm.planetActive=true;});
  await expect(page.locator('.planet-host')).toHaveAttribute('data-planet-state','ready',{timeout:25000});
  await expect(page.locator('.planet-host canvas')).toHaveCount(1);
  console.log('Reactivation creates exactly one scene');
  await page.evaluate(()=>new Promise((resolve,reject)=>uni.navigateTo({url:'/pages/index/index',success:resolve,fail:reject})));
  await page.waitForURL('**/#/pages/index/index');
  await expect(page.locator('.planet-host canvas')).toHaveCount(0);
  console.log('Leaving login disposes canvas');
  const fallback=await context.newPage();
  fallback.on('pageerror',e=>errors.push(e.message));
  await fallback.route('**/static/web/login-planet/scene.js',route=>route.abort());
  await fallback.goto(baseURL,{waitUntil:'networkidle'});
  await expect(fallback.locator('.planet-host')).toHaveAttribute('data-planet-state','fallback',{timeout:20000});
  await expect(fallback.locator('.planet-poster')).toBeVisible();
  await fallback.locator('.login-page .nexus-button--block').click();
  await expect(fallback.locator('.nexus-field__message--error')).toHaveCount(2);
  console.log('Runtime failure keeps poster and working form');
  const lost=await context.newPage();
  lost.on('pageerror',e=>errors.push(e.message));
  await lost.goto(baseURL,{waitUntil:'networkidle'});
  await expect(lost.locator('.planet-host')).toHaveAttribute('data-planet-state','ready',{timeout:25000});
  await lost.locator('.planet-host canvas').evaluate(canvas=>{const gl=canvas.getContext('webgl2');gl.getExtension('WEBGL_lose_context').loseContext();});
  await expect(lost.locator('.planet-host')).toHaveAttribute('data-planet-state','fallback');
  await expect(lost.locator('.planet-host canvas')).toHaveCount(0);
  await expect(lost.locator('.planet-poster')).toBeVisible();
  console.log('WebGL context loss returns to poster and removes canvas');
  assert.deepEqual(errors,[]);
  console.log('No page runtime errors');
 } finally {await browser.close();}
})().catch(e=>{console.error(e.stack);process.exitCode=1;});
