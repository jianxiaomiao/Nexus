const fs = require('node:fs/promises')
const path = require('node:path')
const assert = require('node:assert/strict')
const { _electron, expect } = require('../../nexus-console/node_modules/@playwright/test')
const root = path.resolve(__dirname, '..')
;(async () => {
  const dir = await fs.mkdtemp(path.join(root, '.runtime', 'short-link-ui-'))
  const env = { ...process.env, NEXUS_SHORT_LINK_BOUNDARY_DIR: dir, NEXUS_DESKTOP_SMOKE: '0', NEXUS_DESKTOP_DIAGNOSE: '0' }
  delete env.ELECTRON_RUN_AS_NODE
  let instance
  try {
    instance = await _electron.launch({ executablePath: require('electron'), args: [path.join(__dirname, 'short-link-ui-main.cjs')], env })
    const page = await instance.firstWindow()
    await page.waitForURL('nexus://app/login')
    await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async value => { window.__copiedShortLink = value } } }))
    await page.getByPlaceholder('请输入邮箱').fill('ui@example.test')
    await page.getByPlaceholder('请输入密码').fill('TEST_ONLY')
    await page.getByRole('button', { name: '登录', exact: true }).click()
    await page.waitForURL('nexus://app/applications')
    await page.getByRole('link', { name: 'API 调试台', exact: true }).click()
    await page.getByRole('button', { name: '短链接', exact: true }).click()
    await page.getByLabel('API Key', { exact: true }).fill('UI_TEST_ONLY')
    await page.getByLabel('短链名称', { exact: true }).fill('界面验收短链')
    await page.getByLabel('原始 HTTPS 地址').fill('https://weibo.com/1')
    await page.getByRole('button', { name: '发送请求', exact: true }).click()
    const created = page.locator('.playground-created-link')
    const target = 'http://localhost:8080/s/Ab12Cd34Ef56'
    await expect(created.locator('code')).toHaveText(target)
    await created.getByRole('button', { name: '复制短地址', exact: true }).click()
    assert.equal(await page.evaluate(() => window.__copiedShortLink), target)
    await instance.evaluate(() => { globalThis.__shortLinkBoundary.mode = 'pending' })
    const open = created.getByRole('button', { name: '打开短地址', exact: true })
    await open.click()
    await expect(open).toBeDisabled()
    await expect.poll(() => instance.evaluate(() => globalThis.__shortLinkBoundary.calls.length)).toBe(1)
    await instance.evaluate(() => globalThis.__shortLinkBoundary.release())
    await expect(open).toBeEnabled()
    await instance.evaluate(() => { globalThis.__shortLinkBoundary.mode = 'reject' })
    await open.click()
    await expect(page.getByText('无法打开短地址，请复制后在浏览器中访问', { exact: true })).toBeVisible()
    await expect(open).toBeEnabled()
    await instance.evaluate(() => { globalThis.__shortLinkBoundary.mode = 'success'; globalThis.__shortLinkUiList = true })
    await page.getByRole('button', { name: '查询列表', exact: true }).click()
    await page.getByRole('button', { name: '发送请求', exact: true }).click()
    const listed = page.locator('.playground-link-item')
    await listed.getByRole('button', { name: target, exact: true }).click()
    await listed.getByRole('button', { name: '复制短地址', exact: true }).click()
    assert.equal(await page.evaluate(() => window.__copiedShortLink), target)
    assert.equal(await listed.locator('a[target=_blank]').count(), 0)
    await page.getByRole('link', { name: '短链接', exact: true }).click()
    await expect(page.locator('.short-links-table')).toContainText(target)
    const manager = page.locator('.short-links-table')
    await manager.getByRole('button', { name: '打开 界面验收短链 的短地址', exact: true }).click()
    await manager.getByRole('button', { name: '复制 界面验收短链 的短地址', exact: true }).click()
    assert.equal(await page.evaluate(() => window.__copiedShortLink), target)
    await page.setViewportSize({ width: 390, height: 844 })
    const mobile = page.locator('.short-links-mobile-list')
    await expect(mobile).toBeVisible()
    await mobile.getByRole('button', { name: '打开 界面验收短链 的短地址', exact: true }).click()
    const calls = await instance.evaluate(() => globalThis.__shortLinkBoundary.calls)
    assert.equal(calls.length, 5)
    assert.ok(calls.every(url => url === target))
    await fs.writeFile(path.join(dir, 'evidence.json'), JSON.stringify({ passed: true, calls, copied: target, actualBrowserOpened: false }, null, 2))
    console.log('PASS: built desktop create/list/management/mobile buttons, fixed HTTP display/copy, pending/failure/recovery and exact real IPC targets')
    console.log(`Evidence: ${dir}`)
  } finally { await instance?.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
